"""tenkm.init: prepare a loop directory.

    10km init      create the database if there is none, and register the
                   central repos: record each one's branch (tenkm.mainBranch)
                   and install the loop's git hooks, where not already set.

Hooks: init generates a hooks dir for each repo, tenkm-hooks/ in the repo's git
common dir, and sets the repo's own (local) core.hooksPath to it unless the repo
already sets one of its own. The generated dir holds prepare-commit-msg, which runs
the loop's hooks/prepare-commit-msg (the Loop-Session trailer), and, for a
core.hooksPath inherited from system or global config, a wrapper for each hook
that dir has, which runs it with the same arguments and stdin. The inherited path
is written into the wrappers, so a hook run costs no git process, and hook names
the inherited dir lacks run nothing. Rerun init after the inherited dir gains or
loses a hook.

Kickoff (`10km kickoff`) calls this; run it again after adding a repo to central/.
The central worktrees are the source of truth for which repos the loop has: init
never clones or creates project repos. `create_loop_repo` makes a loop repo from a
copy of 10km, for the container's first start and for tests.
"""
import os
import shlex
import shutil
import subprocess

from . import gitutil, msm
from .config import CODE_ROOT


def create_loop_repo(dest, source=CODE_ROOT, branch="main"):
    """Create a loop repo at dest from a copy of the 10km code, with one commit."""
    shutil.copytree(source, dest, symlinks=True,
                    ignore=shutil.ignore_patterns(".git", "__pycache__", "*.db*", ".#*", "*~"))
    env = dict(os.environ)
    env.setdefault("GIT_AUTHOR_NAME", "10km")
    env.setdefault("GIT_AUTHOR_EMAIL", "10km@localhost")
    env.setdefault("GIT_COMMITTER_NAME", env["GIT_AUTHOR_NAME"])
    env.setdefault("GIT_COMMITTER_EMAIL", env["GIT_AUTHOR_EMAIL"])
    for args in (["init", "-q", "-b", branch], ["add", "-A"], ["commit", "-q", "-m", "Loop repo"]):
        subprocess.run(["git", "-C", dest, *args], env=env, check=True, capture_output=True)


def run(cfg):
    """Create the database if needed and register the central repos. Safe to rerun."""
    loop = cfg.repo_path("loop")
    if not os.path.exists(os.path.join(loop, ".git")):
        raise msm.MSMError(msm.ENOENT, f"no loop repo at {loop}; run 10km from a loop "
                                       "directory, or set LOOP_ROOT")
    report = {}
    with msm.transaction(cfg.db, create=True) as m:
        if m.one("SELECT name FROM sqlite_master WHERE name = 'loop'"):
            report["database"] = "existing"
        else:
            m.init()
            report["database"] = "created"
    hooks = os.path.join(loop, "hooks")
    for repo in cfg.repos():
        path = cfg.repo_path(repo)
        if not gitutil.ok(cfg, path, "config", "--get", "tenkm.mainBranch"):
            gitutil.git(cfg, path, "config", "tenkm.mainBranch",
                        gitutil.git(cfg, path, "symbolic-ref", "--short", "HEAD"))
        install_hooks(cfg, path, hooks)
        report[repo] = gitutil.main_branch(cfg, repo)
    return report


# The hook names git runs (githooks(5)); only these are chained.
HOOK_NAMES = (
    "applypatch-msg", "pre-applypatch", "post-applypatch", "pre-commit",
    "pre-merge-commit", "prepare-commit-msg", "commit-msg", "post-commit",
    "pre-rebase", "post-checkout", "post-merge", "pre-push", "pre-receive", "update",
    "proc-receive", "post-receive", "post-update", "reference-transaction",
    "push-to-checkout", "pre-auto-gc", "post-rewrite", "sendemail-validate",
    "fsmonitor-watchman", "p4-changelist", "p4-prepare-changelist",
    "p4-post-changelist", "p4-pre-submit", "post-index-change",
)
GENERATED = "tenkm-hooks"


def _same_dir(a, b):
    return os.path.realpath(a) == os.path.realpath(b)


def hooks_dir(cfg, path):
    """The repo's generated hooks dir: tenkm-hooks/ in its git common dir, which
    the repo's worktrees share."""
    common = gitutil.git(cfg, path, "rev-parse", "--git-common-dir")
    return os.path.abspath(os.path.join(path, common, GENERATED))


def inherited_hooks(inherited):
    """The hook names the inherited hooks dir has, as executable files."""
    if not inherited or not os.path.isdir(inherited):
        return []
    return [name for name in HOOK_NAMES
            if os.path.isfile(os.path.join(inherited, name))
            and os.access(os.path.join(inherited, name), os.X_OK)]


def _hook_script(name, hooks, inherited, chained):
    """The generated hook `name`: the loop's own hook, if it has one, then the
    inherited hook of that name, if chained (skipped if it has gone since)."""
    lines = ["#!/bin/sh", "# Generated by 10km init (tenkm/init.py); rerun init to update."]
    own = os.path.join(hooks, name)
    target = shlex.quote(os.path.join(inherited, name)) if chained else None
    if os.path.isfile(own):
        if not target:
            return "\n".join(lines + [f'exec {shlex.quote(own)} "$@"']) + "\n"
        lines.append(f'{shlex.quote(own)} "$@" || exit')
    lines += [f"[ -x {target} ] || exit 0", f'exec {target} "$@"']
    return "\n".join(lines) + "\n"


def write_hooks(gen, hooks, inherited):
    """Make gen hold the loop's hooks plus wrappers for the inherited hooks, and
    nothing else. Each file is replaced atomically, so a crash leaves working hooks."""
    chained = set(inherited_hooks(inherited))
    names = {n for n in HOOK_NAMES if os.path.isfile(os.path.join(hooks, n))} | chained
    os.makedirs(gen, exist_ok=True)
    for name in sorted(names):
        tmp = os.path.join(gen, f".{name}.tmp")
        with open(tmp, "w") as f:
            f.write(_hook_script(name, hooks, inherited, name in chained))
        os.chmod(tmp, 0o755)
        os.replace(tmp, os.path.join(gen, name))
    for name in os.listdir(gen):
        if name not in names:
            os.remove(os.path.join(gen, name))
    return sorted(names)


def install_hooks(cfg, path, hooks):
    """Point the repo at its generated hooks dir, chaining to any inherited one.

    Only the repo's local core.hooksPath counts: if it is set to anything other
    than a loop-installed dir (the generated one, or the loop's hooks/ from before
    it), leave the repo alone. Otherwise regenerate the dir and set it. The
    inherited dir is the core.hooksPath from global or system config (global
    wins, as in git); a loop-installed one is never chained to. Reads config with
    --show-scope (git 2.26+), so it sees what git itself uses.
    """
    _, out, _ = gitutil.run(cfg, path, "config", "--show-scope", "--type=path", "--get-all",
                            "core.hooksPath")
    values = dict(line.split("\t", 1) for line in out.splitlines() if "\t" in line)
    gen = hooks_dir(cfg, path)
    local = values.get("local", "")
    if local and not (_same_dir(local, hooks) or _same_dir(local, gen)):
        return
    inherited = values.get("global") or values.get("system", "")
    if inherited and (_same_dir(inherited, hooks) or _same_dir(inherited, gen)):
        inherited = ""
    write_hooks(gen, hooks, inherited)
    if not (local and _same_dir(local, gen)):
        gitutil.git(cfg, path, "config", "--local", "core.hooksPath", gen)
    # Set by earlier versions, whose hooks read it on every run.
    gitutil.git(cfg, path, "config", "--local", "--unset-all", "tenkm.chainHooksPath",
                check=False)
